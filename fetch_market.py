SESSION = requests.Session()
SESSION.headers.update({
    "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/130 Safari/537.36",
    "Referer": "https://data.eastmoney.com/",
    "Accept": "application/json,text/plain,*/*",
})


def get_json(url, params, retries=4):
    last_error = None
    for i in range(retries):
        try:
            r = SESSION.get(url, params=params, timeout=15)
            r.raise_for_status()
            return r.json()
        except Exception as exc:
            last_error = repr(exc)
            time.sleep(0.8 * (i + 1))
    raise RuntimeError(last_error)


def fetch_one(code, name, board, category, exposure):
    secid = ("1." if code.startswith("6") else "0.") + code
    out = {
        "date": TARGET_DATE,
        "code": code,
        "name": name,
        "board": board,
        "category": category,
        "exposure": exposure,
        "close": None,
        "pct_chg": None,
        "amount_yuan": None,
        "turnover_pct": None,
        "main_net_yuan": None,
        "main_net_ratio_pct": None,
        "super_net_yuan": None,
        "big_net_yuan": None,
        "status": "ok",
        "error": "",
    }
    try:
        k = get_json(
            "https://push2his.eastmoney.com/api/qt/stock/kline/get",
            {
                "secid": secid,
                "klt": "101",
                "fqt": "1",
                "end": "20500101",
                "lmt": "15",
                "fields1": "f1,f2,f3,f4,f5,f6,f7",
                "fields2": "f51,f52,f53,f54,f55,f56,f57,f58,f59,f60,f61",
                "ut": "fa5fd1943c7b386f172d6893dbbd1d0c",
            },
        )
        klines = ((k or {}).get("data") or {}).get("klines") or []
        row = next((x for x in klines if str(x).startswith(TARGET_DATE + ",")), None)
        if row:
            p = row.split(",")
            out["close"] = float(p[2])
            out["amount_yuan"] = float(p[6])
            out["pct_chg"] = float(p[8])
            out["turnover_pct"] = float(p[10])
        else:
            out["status"] = "missing_kline"

        f = get_json(
            "https://push2his.eastmoney.com/api/qt/stock/fflow/daykline/get",
            {
                "secid": secid,
                "klt": "101",
                "lmt": "15",
                "fields1": "f1,f2,f3,f7",
                "fields2": "f51,f52,f53,f54,f55,f56,f57,f58",
                "ut": "b2884a393a59ad64002292a3e90d46a5",
            },
        )
        flows = ((f or {}).get("data") or {}).get("klines") or []
        fr = next((x for x in flows if str(x).startswith(TARGET_DATE + ",")), None)
        if fr:
            p = fr.split(",")
            out["main_net_yuan"] = float(p[1])
            out["big_net_yuan"] = float(p[4])
            out["super_net_yuan"] = float(p[5])
            out["main_net_ratio_pct"] = float(p[6])
        else:
            out["status"] = "missing_flow" if out["status"] == "ok" else out["status"] + "+missing_flow"
    except Exception as exc:
        out["status"] = "error"
        out["error"] = repr(exc)
    return out


def main():
    rows = []
    for idx, item in enumerate(UNIVERSE, 1):
        rows.append(fetch_one(*item))
        if idx % 10 == 0:
            print(f"fetched {idx}/{len(UNIVERSE)}", flush=True)
        time.sleep(0.08)

    fields = list(rows[0].keys())
    with Path("market_20260807.csv").open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)

    payload = {
        "target_date": TARGET_DATE,
        "source": "Eastmoney public kline and historical fund-flow endpoints",
        "fund_flow_definition": "main_net = super-large order net + large order net, Eastmoney transaction-size classification",
        "rows": rows,
    }
    Path("market_20260807.json").write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")

    ok = [r for r in rows if r["main_net_yuan"] is not None and r["pct_chg"] is not None]
    print(json.dumps({"total": len(rows), "ok": len(ok), "errors": len(rows)-len(ok)}, ensure_ascii=False))


if __name__ == "__main__":
    main()
